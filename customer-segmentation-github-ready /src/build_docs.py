def r(x, d=0):
    return float(Decimal(str(float(x))).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP))


def f(x, d=0):
    return f"{r(x, d):,.{d}f}"


def usd(x):
    return f"${f(x / 1e6, 2)}m" if x >= 1e6 else f"${f(x / 1e3)}k" if x >= 1e3 else f"${f(x)}"


